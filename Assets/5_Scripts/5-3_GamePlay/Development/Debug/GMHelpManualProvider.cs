    #region 手册目录注册

    // 目录只保存操作说明，发书时不创建 GM 窗口，也不扫描场景对象。
    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
    private static void Register()
    {
        PlayerHelpCatalog.RegisterProvider("flatworld.gm.manual", CollectEntries);
    }

    private static IEnumerable<PlayerHelpEntry> CollectEntries()
    {
        foreach (PlayerHelpEntry entry in ShortcutEntries) yield return entry;
        foreach (PlayerHelpEntry entry in PlayerEntries) yield return entry;
        foreach (PlayerHelpEntry entry in WorldEntries) yield return entry;
        foreach (PlayerHelpEntry entry in SpawnEntries) yield return entry;
        foreach (PlayerHelpEntry entry in DebugEntries) yield return entry;
        foreach (PlayerHelpEntry entry in DeviceEntries) yield return entry;
        foreach (PlayerHelpEntry entry in WeatherEntries) yield return entry;
        foreach (PlayerHelpEntry entry in ModEntries) yield return entry;
    }

