test.runtime("buff", "infection", {}, function(data)
    local function near(actual, expected, label)
        assert(math.abs(actual - expected) < .0001, label .. "：" .. tostring(actual) .. " != " .. tostring(expected))
    end
    local function attributes(sample, attack, ratio, label)
        near(sample.attack, attack, label .. "固定攻击")
        near(sample.speed, 12 * ratio, label .. "移速")
        near(sample.speedMultiplier, 1.5 * ratio, label .. "外部速度倍率")
        near(sample.baseAttack, 10, label .. "武器基础攻击")
        assert(sample.ownerCredit and sample.weaponSource, label .. "多级武器Owner上下文")
    end
    assert(data.added and data.secondAdded and data.thirdAdded and data.fourthAdded and data.overflowAdded and data.sameInstance,
        "正式感染施加、叠层或同实例续期失败")
    attributes(data.one, 9, .75, "正式一层")
    near(data.one.remaining, 300, "首次感染5分钟")
    near(data.beforeStack.phase, 7, "叠层前周期")
    attributes(data.two, 8, .5, "正式二层")
    assert(data.two.stacks == 2, "二次感染没有加到二层")
    near(data.two.remaining, 300, "叠层刷新5分钟")
    near(data.two.phase, 7, "叠层重置了周期相位")
    near(data.secondTickLoss, 2, "7秒后叠层再过3秒必须扣2血")
    attributes(data.three, 7, .25, "正式三层")
    near(data.thirdTickLoss, 3, "三层每10秒扣3血")
    attributes(data.capped, 7, .25, "超限仍三层")
    assert(data.capped.stacks == 3, "额外感染突破三层上限")
    near(data.capped.remaining, 300, "达到上限后仍需续期")
    near(data.capped.phase, 7, "上限续期重置了周期")
    near(data.cappedTickLoss, 3, "上限续期后的原周期没有结算")
    assert(data.presentBeforeExpiry and data.beforeExpiry.stacks == 3, "感染不到5分钟就消失或擅自脱层")
    near(data.beforeExpiry.remaining, 1, "到期前1秒")
    assert(data.absentAfterExpiry, "满5分钟没有移除感染")
    near(data.expiryCycleLoss, 90, "三层5分钟的30次实际扣血")
    attributes(data.expiredRestored, 10, 1, "自然到期恢复")
    assert(data.sourcesDistinct and data.sourceReuse, "来源实例没有独立登记或同来源重复应用")
    attributes(data.twoSources, 7, .5 * .75, "两层来源加一层来源")
    assert(data.oneSourcePresent, "删除一个来源误清全部感染")
    attributes(data.oneSourceLeft, 9, .75, "仅剩一层来源")
    assert(data.regularAddedAlongsideSource, "来源感染阻止常规感染")
    attributes(data.sourceAndRegular, 8, .75 * .75, "来源和常规共存")
    assert(data.sourceSurvivedRegularRemoval, "删除常规感染误清来源实例")
    attributes(data.afterRegularRemoval, 9, .75, "移除常规后来源保持")
    assert(data.allSourcesRemoved, "感染来源全部删除后仍遗留状态")
    attributes(data.sourcesRestored, 10, 1, "来源删除后无属性残留")
end, "正式感染三层叠加、周期续期、自然到期和属性归还")
