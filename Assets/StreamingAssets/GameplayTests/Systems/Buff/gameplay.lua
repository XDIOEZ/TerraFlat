-- 使用真实玩家、正式目录和 Buff 管理器，不写测试专用状态字段。
test.check("player_ready", "真实玩家就绪")
test.gm("enable_admin")
test.gm("remove_self_buff", "core:night_vision")
test.check("gm_buff_absent:core:night_vision", "前置夜视状态清除")
test.runtime("buff", "source_presence", {}, function(data)
    assert(data.initialAbsent and data.emptyAbsent, "初始状态或空定义查询错误")
    assert(data.firstPresent and data.sourceCaseMatches and not data.sourceOnlyRegularKey and data.firstCount == 1, "仅来源实例未按定义身份存在")
    assert(data.sameSourceReused and data.twoSourcesPresent and data.twoSourcesDistinct and data.twoSourceCount == 2, "同来源复用或同定义双来源隔离错误")
    assert(data.afterFirstPresent and data.afterFirstCount == 1, "删除一个来源误判同定义全部不存在")
    assert(data.afterAllAbsent and data.afterAllCount == 0, "全部来源删除后仍查询到定义")
    assert(data.regularAdded and data.regularPresent and data.regularCaseMatches and data.regularKeyPresent, "常规 Buff 定义键查询回归")
    assert(data.coexistingSourceCount == 1 and data.sourceAfterRegularRemoved and data.regularKeyRemoved, "删除常规实例误清或漏查独立来源")
    assert(data.restoredAbsent and data.restoredCount, "来源身份现场未恢复原 Buff 集合")
end, "正式 Buff 定义身份与独立来源增删")
test.runtime("buff", "bleeding_sources", {}, function(data)
    assert(data.sourceOnlyPresent and data.sourceOnlyRegularAbsent, "独立出血来源被误当成常规实例键")
    assert(data.sourceOnlyLowerAccepted and data.sourceOnlyLowerRegular and data.sourcePreservedAfterLower, "仅高等级来源时低等级常规出血抛错或误续来源")
    assert(data.highRegularApplied and data.regularSourceDistinct and data.lowRegularRemoved, "同定义来源与常规出血没有独立共存")
    assert(data.regularDurationSet and data.lowerRenewsRegular and data.sameRegularAfterRenew and data.regularDurationIncreased, "低等级命中没有沿用常规高等级续期")
    assert(data.sourceDurationUnchanged and data.sourceAfterRegularRemoved and data.allRemoved, "常规出血更新误改来源或移除后遗留实例")
end, "来源出血隔离与常规出血续期")
