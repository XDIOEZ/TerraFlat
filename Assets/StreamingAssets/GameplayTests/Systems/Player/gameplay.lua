test.runtime("environment", "tile_effect_reenable", {}, function(data)
    local function near(a, b, label)
        assert(type(a) == "number" and math.abs(a - b) < .0001, label)
    end
    local function ice(sample, label)
        assert(sample.active, label .. "没有重建地块接触")
        near(sample.acceleration, .35, label .. "冰面加速响应丢失")
        near(sample.deceleration, .15, label .. "冰面刹车响应丢失")
    end
    local function clear(sample, label)
        assert(not sample.active, label .. "仍保留地块接触")
        near(sample.acceleration, 1, label .. "仍保留旧冰面响应")
        near(sample.deceleration, 1, label .. "仍保留旧冰面刹车响应")
    end
    ice(data.initial, "首次冰面")
    clear(data.disabled, "临时停用")
    ice(data.resumed, "重新启用")
    clear(data.transitionBlocked, "正式迁移准备后启停")
    clear(data.transitionWhileDisabled, "停用期间进入正式迁移")
    ice(data.transitionReady, "正式世界就绪")
    clear(data.suppressed, "承载抑制期间启停")
    ice(data.released, "抑制解除")
    near(data.snowInitial.speed, data.normalSpeed * data.snowMultiplier, "首次雪层减速错误")
    near(data.snowDisabled.speed, data.normalSpeed, "停用后雪层减速没有撤销")
    near(data.snowResumed.speed, data.snowInitial.speed, "重新启用后雪层减速丢失或重复")
    assert(data.changedWhileDisabled.active and data.reloaded.active, "新地表或正式重载后接触未建立")
    near(data.changedWhileDisabled.acceleration, 1, "停用期间换地块后恢复了旧冰面")
    near(data.changedWhileDisabled.speed, data.normalSpeed, "停用期间铲雪后恢复了旧减速")
    near(data.reloaded.acceleration, 1, "正式重载后残留旧冰面响应")
end, "冰面与积雪接触启停恢复，保留迁移和承载门禁并读取最新地表")
