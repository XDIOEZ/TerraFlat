test.system("save", "ecology_snapshot_cache", { amount = 3 }, function(data)
    assert(data.initialWork == 5 and data.repeatedWork == 2, "首次按物品分帧或重复保存按区块复用失效")
    assert(data.recordsReused and data.frozenBytesReused, "未变化的生态区块和物品字节没有跨次复用")
    assert(data.runtimeIsolated, "自然物入世后的运行数据改写了生态存档或嵌套库存")
    assert(data.metadataChanged and data.metadataOnlyReusedItems, "坐标、删除列表或恢复年份变化没有重冻元数据，或物品字节被重复生成")
    assert(data.membershipSelective, "新增或替换没有只冻结变化的快照")
    assert(data.harvestAndLateChunk, "采收删除、恢复年份或新建区块没有进入最终快照")
    assert(data.rootSeparated and data.chunkSeparated, "切换存档根或替换区块后串用了旧缓存")
    assert(data.frozenIsolation, "冻结后的源数据变化污染了旧的字节载荷")
    assert(data.overlappingCapture, "交错的保存采集覆盖了最终成员或历史快照")
    assert(data.playerCapturePolicy, "角色本地与网络公开序列化策略串用缓存")
    assert(data.nestedPlayerCapturePolicy, "嵌套角色在私有和不同公开策略之间泄漏库存或复用了旧字节")
    assert(data.codecRevision, "模块编解码器替换后复用了旧的物品字节")
end, "生态冻结缓存复用、采收与快照生命周期")
