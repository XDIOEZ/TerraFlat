-- 正式写盘只允许 Library 测试隔离目录；冷克隆和非发布读取不得替换正在跑的世界。
test.runtime("save", "isolated_roundtrip", { amount = 3 }, function(data)
    assert(data.scope == "live-isolated-world" and data.firstWritten and data.secondWritten and data.firstBytes > 0 and data.secondBytes > 0, "正式隔离存档写入失败")
    assert(data.backupExists and data.backupMatchesFirst and not data.temporaryRemaining, "原子替换备份丢失、错误或残留临时文件")
    assert(data.firstAmount == 3 and data.secondAmount == 4 and data.firstGuid == 910143 and data.secondGuid == 910143, "首次/替换存档的真实库存或持久身份恢复错误")
    assert(data.firstId == "Stick_Wood" and data.secondId == "Stick_Wood", "存档恢复了错误的物品定义")
    assert(data.firstSpecial == '{"probe":1}' and data.secondSpecial == '{"probe":2}', "备份和当前文件没有保存各自状态")
    assert(data.firstPositionPreserved and data.secondPositionPreserved, "存档备份或最新文件丢失了非原点的玩家坐标")
    assert(data.firstPlayers == data.expectedPlayers and data.secondPlayers == data.expectedPlayers, "保存恢复遗漏角色档案")
    assert(data.activeSaveReferencePreserved and data.activePlayerReferencePreserved and data.activeManagerPreserved, "恢复测试替换了活跃世界、角色或管理器")
    assert(data.activeNamePreserved and data.activeSeedPreserved and data.activeCountsPreserved and data.activePlayerStatePreserved and data.activeDirectoryPreserved, "写盘测试污染了当前世界的正式状态")
    assert(string.find(data.path, "FlatWorldGameplayTests", 1, true) ~= nil, "存档报告路径不属于测试目录")
end, "正式隔离保存、原子替换、备份与非发布恢复")
