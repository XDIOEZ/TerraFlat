test.system("ai", "servitor_rules", {}, function(data)
    assert(data.lowRequested and data.lowStored == 1999, "低电量没有请求回充")
    assert(data.requestedWatts == 100 and data.halfSecondStored == 2049, "半秒充电不是满容量的0.5%")
    assert(data.rechargeLatched and data.restoredIntent and data.restoredStored == 2049, "回充滞回或电量快照丢失")
    assert(data.tailWatts == 1 and data.fullStored == 10000 and not data.fullRequested, "满电边界多取电或不退出充电")
    assert(data.emptyStored == 0 and data.emptyRequested, "耗尽边界没有钳制或请求回充")
    assert(data.terminalBound and data.modulePrefab and data.sprite, "机仆正式资源或终端控件绑定缺失")
    assert(data.actorModuleIdentityDistinct, "机仆实体与模块共用同一资源别名")
    assert(data.footprintSeparateFromHitbox, "机仆把整身受击范围当作脚底移动占地")
    assert(data.shellShapeMatchesDefinition, "机仆外壳没有声明与JSON一致的作者碰撞体")
    assert(data.shellIdentityMatchesDefinition, "机仆外壳仍使用来源动物的资源身份")
end, "机仆电池、充电滞回、持久状态和正式资源")
