test.system("ui_settings", "gm_inspector_ownership", {}, function(data)
    assert(data.separateText and data.separateBuffers, "悬停观察器拆分后串用了目标或查询/文本缓冲")
    assert(data.clearOnlyOwner, "清理一个观察器破坏了另一个观察器的目标和文本")
