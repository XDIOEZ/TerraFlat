-- 主角真正打开背包后，正式任务管理器与教程控制器共同消费成功通知。
test.check("world_ready", "真实隔离世界就绪")
test.check("player_ready", "真实本地主角就绪")
test.runtime("guide", "inventory_quest", {}, function(data)
    assert(data.accepted and data.before.status == "Active", "正式本体调试任务未接取")
    assert((data.before.progress["open_inventory/open_once"] or 0) == 0 and not data.prematureClaim, "开包前任务已经完成或允许提前交付")
    assert(data.panelOpen and data.afterOpen.status == "ReadyToClaim", "真实背包打开没有推进正式任务")
    assert(data.afterOpen.progress["open_inventory/open_once"] == 1, "开包成功没有按实际次数推进")
    assert(data.afterRepeat.progress["open_inventory/open_once"] == 1 and data.afterRepeat.status == "ReadyToClaim", "重复开包越过目标上限或重复完成")
    assert(data.claimed and data.afterClaim.status == "Completed" and not data.duplicateClaim and not data.duplicateAccept, "手动交付或完成后重复领取拒绝错误")
    assert(data.savedStatus == "Completed" and data.savedRewardsClaimed and data.savedCompletionCount == 1, "任务正式进度没有保存唯一完成记录")
    assert(data.guideAfter.active and data.guideAfter.eligible and data.guideAfter.inventoryOpened, "真实开包没有被已加载教程消费")
    assert(data.guideAfter.stage ~= "OpenInventory" and data.guideAfter.savedStage == data.guideAfter.stage, "教程缓存阶段与正式保存进度不一致")
    assert(data.guideAfter.facts["tutorial.enabled"] == "True" and data.guideAfter.facts["tutorial.stage"] == data.guideAfter.stage, "教程没有向实际对话上下文贡献当前阶段")
    assert(data.panelRestored, "测试改变了原主背包开关状态")
end, "实际开包贯穿任务和新手引导")
