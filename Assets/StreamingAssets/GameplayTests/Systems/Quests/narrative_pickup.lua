-- 调用实际主角拾取模块的入包事务，任务与教程只监听生产代码产生的成功信号。
test.check("world_ready", "真实隔离世界就绪")
test.check("player_ready", "真实主角就绪")
test.runtime("guide", "pickup_quest", {}, function(data)
    assert(data.accepted and data.before.status == "Active", "正式拾取任务未接取")
    assert(data.firstPickup and data.afterFirst.status == "Active" and data.afterFirst.progress["pickup_items/pickup_three"] == 2, "实际拾取两根没有推进两件任务进度")
    assert(data.secondPickup and data.afterSecond.status == "Completed" and data.afterSecond.progress["pickup_items/pickup_three"] == 3, "第三件入包后任务没有自动完成")
    assert(#data.signals == 2 and data.signals[1].amount == 2 and data.signals[2].amount == 1, "成功入包的正式信号数量或金额不正确")
    assert(data.signals[1].target == "Stick_Wood" and data.signals[2].target == "Stick_Wood", "实际入包物品与任务信号不一致")
    assert(data.inventoryCountAfter == data.inventoryCountBefore + 3, "只有任务计数变化，真实库存没有增加三根木棍")
    assert(data.savedCompletionCount == 1 and not data.duplicateClaim, "自动完成重复登记或重复领奖")
    assert(data.inventoryCountRestored == data.inventoryCountBefore, "自有拾取物未按正式库存快照恢复")
    assert(data.guideAfter.active and data.guideAfter.savedStage == data.guideAfter.stage and data.guideAfter.savedCompleted == data.guideAfter.completed, "拾取后教程运行态与存储态不一致")
    assert(data.guideAfter.facts["tutorial.stage"] == data.guideAfter.stage, "拾取后的对话 Facts 没有使用真实教程阶段")
    assert(#data.guideAfter.milestones >= #data.guideBefore.milestones and #data.guideAfter.milestones <= #data.guideBefore.milestones + 1, "同一次材料拾取重复增加教程里程碑")
end, "实际入包事务驱动任务自动交付和教程")
