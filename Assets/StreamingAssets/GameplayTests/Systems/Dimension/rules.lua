test.system("dimension", "cave_exit_cache_distance", {}, function(data)
    assert_cave_unchanged(data.before, data.stationary, "站立不动连续100次采样")
    assert(math.abs(data.moved.factor - 0.8) < 0.0001, "移动20米后没有按正式出口距离更新采光")
    assert(data.moved.distanceEvaluations == data.stationary.distanceEvaluations + 1, "移动后没有恰好更新一次距离")
    assert(data.unwrapped.factor == 0 and math.abs(data.wrapped.factor - 0.99) < 0.0001, "切到环绕拓扑后没有采用接缝最短距离")
    assert(data.wrapped.distanceEvaluations == data.unwrapped.distanceEvaluations + 1, "环绕开关变化没有刷新距离")
    assert(data.changedMin.distanceEvaluations == data.wrapped.distanceEvaluations + 1, "相同位置的拓扑原点变化没有刷新距离")
    assert(math.abs(data.changedMin.factor - 0.99) < 0.0001, "拓扑原点变化后接缝采光失真")
    assert(data.changedSpan.distanceEvaluations == data.changedMin.distanceEvaluations + 1 and data.changedSpan.factor == 0, "拓扑跨度变化后仍复用旧最短距离")
    assert(data.changedSpan.positionsRefreshes == data.before.positionsRefreshes, "只有玩家位置或拓扑变化时错误重建了出口集合")
    assert(data.cleared.factor == 1 and data.cleared.positionsRefreshes == data.changedSpan.positionsRefreshes + 1, "清理后没有重新取得出口集合")
    assert(data.cleared.distanceEvaluations == data.changedSpan.distanceEvaluations + 1, "清理后没有重新计算采光")
end, "站立采光复用、玩家移动及环绕拓扑开关原点跨度失效")

