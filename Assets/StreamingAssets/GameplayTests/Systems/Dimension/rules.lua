local function assert_cave_rebuild(previous, current, label)
    assert(current.revision > previous.revision, label .. "没有更新真实出口进度版本")
    assert(current.positionsRefreshes == previous.positionsRefreshes + 1, label .. "没有恰好重建一次出口集合")
    assert(current.distanceEvaluations == previous.distanceEvaluations + 1, label .. "没有恰好重新计算一次出口距离")
end

local function assert_cave_unchanged(previous, current, label)
    assert(current.revision == previous.revision, label .. "错误更新了出口进度版本")
    assert(current.positionsRefreshes == previous.positionsRefreshes, label .. "重复刷新了出口集合")
    assert(current.distanceEvaluations == previous.distanceEvaluations, label .. "重复计算了出口距离")
    assert(current.factor == previous.factor and current.openCount == previous.openCount, label .. "改变了现有采光结果")
end

