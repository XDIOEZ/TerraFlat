test.check("world_ready")
test.runtime("industrial_fluids", "natural_fill", {}, function(d)
    assert(d.filled and not d["repeat"], "自然补气或满限拒绝错误")
    assert(math.abs(d.amount-d.capacity*d.fraction)<.000001, "自然补气未限制在配置占比")
    assert(math.abs(d.sourceTakenLiters-d.amount)<.000001, "自然补气没有扣真实来源")
    assert(not d.highFill and d.higherBefore==d.higherAfter and d.sourceStable, "超过自然上限的气体被排空")
end, "固定罐自然20%补气与来源守恒")
test.runtime("industrial_fluids", "filler", {}, function(d)
    assert(d.slots==3 and d.savedSlots==3, "装填设备或快照不足三个真实槽")
    assert(math.abs(d.firstStep[1]-20)<.000001 and d.firstStep[2]>0 and d.firstStep[3]==0, "未按0到2顺序装满")
    for _, amount in ipairs(d.final) do assert(math.abs(amount-20)<.000001, "实际铁罐未装到固定容量") end
    assert(math.abs(d.sourceAfter+60-(100+d.initialPortable))<.000001, "三槽装填造料或丢料")
end, "三个真实便携铁罐顺序装填及持久化")
