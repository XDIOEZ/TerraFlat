test.runtime("industrial_fluids", "outlet", {}, function(d)
    assert(d.zeroAccepted and d.rateAccepted and d.stopped==100, "零速率未停止排放")
    assert(math.abs((100-d.after)-2*d.seconds)<.000001, "出口未按实际每秒速率扣量")
