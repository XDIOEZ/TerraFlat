local function near(actual, expected, label)
    assert(type(actual) == "number" and math.abs(actual - expected) < 0.0001, label)
end

test.system("environment", "greenhouse_temperature", {}, function(data)
    near(data.zero, 0, "零CO₂基线不应自动增温")
    near(data.scale, 3, "有效CO₂光学量翻倍应增温3℃")
    near(data.tripleScale, 6, "温室增温没有按对数增加")
    near(data.relativeScale, 3, "温室偏移没有扣除星球初始CO₂基线")
    near(data.clampedHigh, 60, "温室增温没有上限")
    near(data.clampedLow, -30, "CO₂减少后的降温没有下限")
    near(data.extremeEqual, 0, "极端有限气柱相等时产生NaN或非零偏移")
    near(data.missing, 0, "缺失大气产生额外温室增温")
    near(data.empty, 0, "零基线真空产生温室增温")
    near(data.beforeEmission, 0, "排气前温度基线不正确")
    near(data.retained, 0.4, "真实大气没有接收排入的CO₂")
    assert(data.emissionRevisionChanged, "实际排气没有使同帧温度缓存失效")
    near(data.afterEmission, 3, "真实CO₂排放没有改变世界温差")
    near(data.otherGasReduced, 3, "抽走其他气体仅提高比例却凭空增加温室效应")
    near(data.thinnerSameFraction, 3 * math.log(1.1) / math.log(2), "温室效应只看比例而忽略真实气柱")
    near(data.afterSecondEmission, 6, "二次排放没有读取最新库存")
    near(data.repeatedRead, 6, "读取温度反复累加温室偏移")
    assert(data.sourceRevisionChanged, "飞船/手动装气来源扣气没有使温室缓存失效")
    near(data.sourceBefore, 3, "适配来源抽气前温差错误")
    near(data.sourceAfter, 3 * math.log(1.5) / math.log(2), "真实来源抽气后仍沿用旧CO₂温差")
    near(data.unregisteredInitial, 0, "未登记目录的星球地表初始大气无法读取自身温室基线")
    assert(data.initialPartialPressure > 0, "含CO₂大气没有冻结初始气柱")
    near(data.cloneBaseline, data.initialPartialPressure, "克隆丢失初始CO₂气柱")
    near(data.binaryBaseline, data.initialPartialPressure, "二进制存档丢失初始CO₂气柱")
    near(data.jsonBaseline, data.initialPartialPressure, "JSON快照丢失初始CO₂气柱")
    near(data.repairBaseline, data.initialPartialPressure, "大气基准恢复没有取初始CO₂气柱")
    assert(data.repairPreservedInventory, "基准恢复错误重灌真实库存")
    near(data.cloneOffset, 0, "克隆初始大气出现假增温")
    near(data.binaryOffset, 0, "二进制读档出现假增温")
    near(data.jsonOffset, 0, "JSON读档出现假增温")
    near(data.firstPlanet, 8, "第一星球全局调温与温室温差没有只叠加一次")
    near(data.secondPlanet, 2, "第一星球CO₂污染了另一星球温度")
    near(data.firstPlanetRepeated, 8, "多星球来回读取造成温差累加")
    near(data.candidateOffset, 14, "候选温室配置没有独立生效")
    near(data.afterCandidateRollback, 8, "候选配置未发布却改变运行星球温度")
    assert(data.candidateKeptInventory, "资源候选回滚改写真实气体库存")
    for _, rejected in ipairs(data.invalidRejected) do
        assert(rejected, "非法CO₂气柱没有被拒绝")
    end
end, "CO₂气柱增温、真实抽排、初始基准、世界隔离、存档与配置回滚")
