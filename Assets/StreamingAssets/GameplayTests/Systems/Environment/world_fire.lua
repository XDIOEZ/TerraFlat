test.system("environment", "world_fire", {}, function(s)
    local function near(actual, expected)
        assert(math.abs(actual - expected) < 0.0001, "火场数值偏离正式规则")
    end
    near(s.steadyFire, 1)
    near(s.consumedSeconds, 1)
    near(s.exhaustedFire, 0)
    near(s.exhaustedConsumption, 0.5)
    near(s.zeroProbability, 0)
    near(s.certainProbability, 1)
    near(s.newConsumption, 0)
    near(s.noNeighbour, 0)
    near(s.hundredSecondsFire, 0)
    near(s.hundredSecondsConsumed, 100)
    assert(s.probabilityPerCycle, "点燃概率被错误换算为每秒概率")
    near(s.remainingFuel, 60)
    near(s.combinedProbability, 0.4)
    near(s.combinedFuel, 130)
    near(s.repeatedSourceFuel, 130)
    near(s.removedSourceFuel, 80)
    near(s.editedProbability, 0.001)
    near(s.editedFuel, 1000)
    near(s.exhaustedSavedFuel, 0)
    near(s.fuelSaveRoundTrip, 1000)
    near(s.migratedConsumedFuel, 42)
    near(s.sameMaterialRemainingFuel, 800)
    near(s.newMaterialRemainingFuel, 60)
    near(s.rehydratedSourceFuel, 60)
    near(s.absoluteEditedFuel, 10)
    near(s.absoluteEditedProbability, 0)
    assert(s.newMaterialConsumptionNotifications == 1, "基料替换没有通知消耗差量变化")
    assert(s.migratedChunkSchema == 2, "SQLite旧火场没有迁移至可燃性层")
    assert(s.exhaustedSavedCells == 2, "烧尽格没有保留差量")
    assert(s.batchNotifications == 1 and s.batchChangedCells == 10000, "万格火势没有合并通知")
    assert(s.activeCount == 10000 and s.removedCount == 9999 and s.restoredCount == 10000, "活火索引或恢复不一致")
    near(s.restoredProgress, 3.5)
    assert(s.singleWriteCorrectCell == 255 and s.otherCellPreserved == 128, "单格火势写到了错误格子")
    assert(s.kernelCells == 10000 and s.kernelAllocatedBytes == 0, "万格数值核热路径产生托管分配")
    assert(s.pipelineCells == 10000 and s.pipelineAllocatedBytes == 0, "万格完整火场热路径产生托管分配")
    near(s.pipelineRemainingFuel, 100 - 11 / 60)
    near(s.frontierCrossChunkIgnited, 1)
    near(s.frontierCrossChunkFuel, 9.9)
    assert(s.frontierStableBurningTopology, "燃料进度变化错误触发火格拓扑重建")
    near(s.frontierExhaustedSource, 0)
    near(s.frontierNoIgnitionWithoutFuel, 0)
    assert(s.frontierSwapSameCount == 1 and s.frontierSwapTopologyChanged,
        "火格数量不变但位置变化，没有标记拓扑脏数据")
    near(s.frontierSwapNewFuel, 9.9)
    near(s.frontierSwapOldFuel, 9.9)
    assert(s.frontierNoopTopologyStable, "未变化火格仍触发脏数据版本")
    assert(s.rightChunkHeating > 0 and s.upperChunkHeating > 0, "跨区块热场漏掉右侧或上侧火源")
    assert(s.heatActiveChunks == 2 and s.heatActiveChunksAfterExtinguish == 0, "世界活火区块索引未同步")
    near(s.otherWorldHeating, 0)
    near(s.heatAfterExtinguish, 0)
    near(s.frozenHeatPreserved, s.rightChunkHeating)
end, "逐周期点燃概率、燃料倒计时、来源合成、烧尽保存与万格完整模拟")
