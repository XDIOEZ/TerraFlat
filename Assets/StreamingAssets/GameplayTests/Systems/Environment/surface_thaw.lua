local function near(actual, expected, label)
    assert(type(actual) == "number" and math.abs(actual - expected) < 0.0001, label)
end

test.system("environment", "surface_thaw_snow", {}, function(data)
    assert(data.naturalCandidates == 1 and data.partialCandidates == 1, "天然雪或部分融化雪没有进入候选")
    assert(data.coveredCandidates == 0 and data.uncoveredCandidates == 1, "平台遮住/移除没有更新天然雪候选")
    assert(not data.coveredEdited, "隐藏天然雪被转成平台上的动态覆盖")
    near(data.coveredDepth, 0, "平台上凭空产生天然雪")
    near(data.coveredMelted, 0, "平台下不可见天然雪凭空产生融水")
    assert(data.platformWeatherCandidates == 1, "平台上的真实天气雪未加入融雪候选")
    near(data.platformWeatherDepth, .08, "平台上的真实天气雪没有正常融化")
    near(data.platformWeatherMelted, .12, "平台真实天气雪的融水不守恒")
    assert(data.firstEdited, "天然雪暖融没有转成持久化覆盖")
    near(data.firstDepth, .88, "天然雪没有按温差连续融化")
    near(data.firstMelted, .12, "融水量与真实消融雪量不符")
    near(data.visibleAfterRestore, .9, "部分融雪恢复后显示层不正确")
    near(data.afterMelt, 0, "天然雪没有彻底融完")
    assert(data.emptyCandidates == 0, "融完后空雪格仍在地表候选里")
    near(data.coldDepth, 0, "融空后降温导致天然雪凭空复活")
    near(data.newWeatherSnow, .03, "融空后真实降雪无法重新积累")
    near(data.tinyDepth, .028, "不足一显示层的雪量被提前截断")
    assert(data.tinyCandidates == 1, "微小残雪退出候选而无法继续融化")
    near(data.seasonalDepth, .38, "季节覆盖没有真实消融")
    near(data.seasonalBaseline, .5, "季节覆盖未固化而重复供水")
    near(data.seasonalMelted, .12, "季节雪融水量不守恒")
    assert(not data.zeroEdited, "零度没有融化却改写了天然雪")
    near(data.zeroMelted, 0, "零度仍产生融雪")
end, "天然雪连续暖融、保存恢复与冷暖循环不复活")

test.system("environment", "surface_thaw_ice", {}, function(data)
    assert(data.candidate and data.platformProtected and data.backProtected and data.changedGroundProtected,
        "融冰候选拒绝错误，或覆盖了玩家平台、背层和已换地面")
    assert(data.seaBed == 29 and data.seaLevel == 80 and data.seaId == "core:sea_water", "海冰丢失真实底床、水量或盐水身份")
    assert(data.riverBed == 30 and data.riverLevel == 37 and data.riverId == "core:dirty_water", "河冰丢失真实底床、水量或淡水身份")
    near(data.partial, .03, "冰层没有按连续温差渐融")
    near(data.complete, 1, "冰层融化进度未封顶")
    near(data.zeroProgress, .03, "零度继续融冰")
    near(data.coldProgress, .03, "零下继续融冰")
    assert(data.frozenBaseline == 0 and data.thawedBaseline == 80, "未融冰参与水域或融完后没有恢复天然水域身份")
    assert(data.liquidPersisted, "融冰水回到生成基线而丢失保存差量")
end, "天然海冰河冰元数据、融化进度与水域基线")

test.system("environment", "surface_thaw_snapshots", {}, function(data)
    near(data.saveProgress, .37, "融冰进度存档往返丢失")
    near(data.wireProgress, .37, "融冰进度网络载荷往返丢失")
    near(data.saveDepth, .23, "动态雪厚存档往返丢失")
    assert(data.saveEdited and data.badWireRejected and data.badSaveRejected,
        "雪覆盖标记丢失或非法融冰进度未被拒绝")
end, "冰雪快照保存、网络往返与非法进度拒绝")
